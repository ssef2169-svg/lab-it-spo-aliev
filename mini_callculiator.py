# Мини-калькулятор
print("=== Мини-калькулятор ===")

# 1. Запрашиваем у пользователя два числа
# Используем float, чтобы можно было вводить не только целые, но и дробные числа (например, 2.5)
num1 = float(input("Введите первое число: "))
num2 = float(input("Введите второе число: "))

# 2. Выполняем вычисления
summa = num1 + num2
raznost = num1 - num2
proizvedenie = num1 * num2

# 3. Выводим результат на экран
print("\n--- Результаты ---")
print(f"Сумма: {summa}")
print(f"Разность: {raznost}")
print(f"Произведение: {proizvedenie}")
